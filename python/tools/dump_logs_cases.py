#!/usr/bin/env python3
"""Dump what the Python log and firmware code answers, for the Rust core.

    python tools/dump_logs_cases.py ulog       -> src/core/tests/data/ulog_cases.json
    python tools/dump_logs_cases.py all
    python tools/dump_logs_cases.py all --check   # fail when a file is stale

The tests of ``corvus_core::logs`` and ``::firmware`` hold the Rust to these
files, so they are generated by running the Python, never typed. Run it from
``python/`` with an interpreter that has corvus_link installed.
"""
from __future__ import annotations

import json
import math
import pathlib
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
PYTHON_ROOT = HERE.parent
DATA = PYTHON_ROOT.parent / "src" / "core" / "tests" / "data"
sys.path.insert(0, str(PYTHON_ROOT))

STALE: list[str] = []
CHECK = False


def write_text(path: pathlib.Path, text: str) -> None:
    if CHECK:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            STALE.append(str(path.relative_to(DATA)))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")


def write_bytes(path: pathlib.Path, blob: bytes) -> None:
    if CHECK:
        if not path.is_file() or path.read_bytes() != blob:
            STALE.append(str(path.relative_to(DATA)))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(blob)
    print(f"wrote {path}")


def write(name: str, data: object) -> None:
    write_text(DATA / name, json.dumps(data, indent=1, sort_keys=False, ensure_ascii=False) + "\n")


def wire(value: object) -> object:
    """JSON-safe: a float that JSON cannot spell becomes its Python text."""
    if isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            return repr(value)
        return value
    if isinstance(value, dict):
        return {str(k): wire(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [wire(v) for v in value]
    if isinstance(value, bytes):
        return value.hex()
    return value


# ---------------------------------------------------------------------------
# ULog builder
# ---------------------------------------------------------------------------

def msg(kind: str, body: bytes) -> bytes:
    return struct.pack("<HB", len(body), ord(kind)) + body


def header(timestamp: int = 1234) -> bytes:
    from corvus.ulog import MAGIC
    return MAGIC + b"\x01" + struct.pack("<Q", timestamp)


def fmt(text: str) -> bytes:
    return msg("F", text.encode())


def add(msg_id: int, name: str, multi_id: int = 0) -> bytes:
    return msg("A", bytes([multi_id]) + struct.pack("<H", msg_id) + name.encode())


def data(msg_id: int, payload: bytes) -> bytes:
    return msg("D", struct.pack("<H", msg_id) + payload)


def keyed(kind: str, key: str, value: bytes) -> bytes:
    return msg(kind, bytes([len(key)]) + key.encode() + value)


def logged(level: int, timestamp: int, text: str) -> bytes:
    return msg("L", bytes([level]) + struct.pack("<Q", timestamp) + text.encode())


def tagged(level: int, tag: int, timestamp: int, text: str) -> bytes:
    return msg("C", bytes([level]) + struct.pack("<HQ", tag, timestamp) + text.encode())


def dump_log(log) -> dict:
    return wire({
        "start_timestamp": log.start_timestamp,
        "truncated": log.truncated,
        "info": log.info,
        "params": log.params,
        "messages": log.messages,
        "dropouts": [d["duration_ms"] for d in log.dropouts],
        "data": {t: {str(m): cols for m, cols in inst.items()} for t, inst in log.data.items()},
    })


