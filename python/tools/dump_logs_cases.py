def ulog_cases() -> None:
    from corvus import ulog

    cases = []
    for name, blob, topics in ulog_scenarios():
        entry = {"name": name, "blob": blob.hex(), "topics": topics}
        try:
            entry["log"] = dump_log(ulog.read(blob, topics=topics))
        except ulog.UlogError as exc:
            entry["error"] = str(exc)
        cases.append(entry)
    big = ulog.MAX_FILE_BYTES
    ulog.MAX_FILE_BYTES = 32
    try:
        try:
            ulog.read(header() + b"\x00" * 64)
        except ulog.UlogError as exc:
            cases.append({"name": "too_large", "blob": (header() + b"\x00" * 64).hex(),
                          "topics": None, "max_bytes": 32, "error": str(exc)})
    finally:
        ulog.MAX_FILE_BYTES = big
    write("ulog_cases.json", cases)


