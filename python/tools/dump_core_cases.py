                before = len(recorded)
                op = step["op"]
                result: object = None
                if op == "listen":
                    store.add_listener(listener)
                elif op == "tick":
                    clock["now"] = step["to"]
                elif op == "update":
                    store.update(**step["args"])
                elif op == "merge_warning":
                    kwargs = {k: step[k] for k in ("meta", "max_warnings", "event") if k in step}
