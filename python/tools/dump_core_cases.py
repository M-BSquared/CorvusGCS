def store() -> None:
    from corvus.state_store import VehicleStateStore

    probe = VehicleStateStore()
    write("state_defaults.json", _clean(probe.get_snapshot()))
    write("state_store_cases.json", {
        "notify_min_interval": VehicleStateStore.NOTIFY_MIN_INTERVAL,
        "immediate_keys": sorted(VehicleStateStore.IMMEDIATE_KEYS),
        "station_keys": sorted(VehicleStateStore._STATION_KEYS),
        "cases": _store_scenarios(),
    })


def buffers() -> None:
    import queue

    from corvus.sse_buffers import _BoundedSseBuffer, _MultiplexSseBuffer

    def entry(name: str, text: str, level: str) -> dict:
        return {"name": name, "text": text, "level": level}

    runs = [
        ("latest", 4, "put_latest", [1, 2, 3]),
        ("fifo", 3, "put_fifo", [1, 2, 3, 4, 5]),
        ("console_dedupes_and_orders", 5, "put_console", [
            entry("EKF", "a", "info"), entry("EKF", "b", "info"), entry("EKF", "a", "info"),
            entry("SHELL", "x", "info"), entry("SHELL", "x", "info"), entry("EKF", "c", "error"),
        ]),
        ("console_evicts_the_newest_quiet_line", 3, "put_console", [
            entry("A", "1", "info"), entry("A", "2", "warning"), entry("A", "3", "info"),
            entry("A", "4", "info"), entry("A", "5", "error"),
        ]),
        ("console_drops_a_quiet_line_when_full_of_urgent", 2, "put_console", [
            entry("A", "1", "error"), entry("A", "2", "critical"), entry("A", "3", "info"),
            entry("A", "4", "warning"),
        ]),
    ]
    cases = []
    for name, capacity, op, items in runs:
        buf = _BoundedSseBuffer(capacity)
        for item in items:
            getattr(buf, op)(item)
        size = buf.qsize()
        first = buf.get(timeout=0)
        rest = buf.drain()
        try:
            buf.get(timeout=0)
            empty = False
        except queue.Empty:
            empty = True
        cases.append({"name": name, "capacity": capacity, "op": op, "items": items,
                      "qsize": size, "first": first, "rest": rest, "then_empty": empty})

    mux = _MultiplexSseBuffer()
    params = mux.topic("params", 16)
    console = mux.topic("console", 3)
    fleet = mux.topic("fleet", 1)
    firmware = mux.topic("firmware", 2)
    params.put_latest({"n": 1})
    params.put_latest({"n": 2})
    console.put_console(entry("A", "x", "info"))
    console.put_console(entry("A", "y", "error"))
    fleet.put_latest({"f": 1})
    fleet.put_latest({"f": 2})
    for i in range(4):
        firmware.put_fifo({"p": i})
    first = mux.drain(timeout=0)
    try:
        mux.drain(timeout=0)
        again_empty = False
    except queue.Empty:
        again_empty = True
    write("sse_buffer_cases.json", {
        "cases": cases,
        "mux": {"topics": [["params", 16], ["console", 3], ["fleet", 1], ["firmware", 2]],
                "drained": [[t, e] for t, e in first], "then_empty": again_empty},
    })


COMMANDS = {"routes": routes, "store": store, "buffers": buffers}


def main(argv: list[str]) -> int:
    global CHECK
    CHECK = "--check" in argv
    names = [a for a in argv[1:] if a != "--check"] or ["all"]
    for name in names:
        if name == "all":
            for fn in COMMANDS.values():
                fn()
        elif name in COMMANDS:
            COMMANDS[name]()
        else:
            print(f"unknown command {name}; one of {', '.join(COMMANDS)} or all", file=sys.stderr)
            return 2
    if STALE:
        print("stale: " + ", ".join(STALE) + "; run tools/dump_core_cases.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
