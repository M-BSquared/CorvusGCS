#!/usr/bin/env python3
"""Dump what the Python backend answers into fixtures for the Rust core.

    python tools/dump_core_cases.py routes   -> src/core/tests/data/python_routes.json
    python tools/dump_core_cases.py all

The Rust tests of ``corvus_core`` hold the core to these files, so they are
generated by running the Python, never typed. Run it from ``python/`` with an
interpreter that has corvus_link installed (``maturin develop`` in src/link).
"""
from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PYTHON_ROOT = HERE.parent
DATA = PYTHON_ROOT.parent / "src" / "core" / "tests" / "data"
sys.path.insert(0, str(PYTHON_ROOT))


def write(name: str, data: object) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    path = DATA / name
    path.write_text(json.dumps(data, indent=2, sort_keys=False, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path}")


def routes() -> None:
    from corvus import server

    handler = server.CorvusHandler
    out = {
        "get": sorted(handler._GET_ROUTES),
        "post": sorted(handler._POST_ROUTES),
        # Dispatched by hand in do_GET / do_POST / do_DELETE, not by @route.
        "extra_get": ["/mcp"],
        "extra_post": ["/mcp", "/api/firmware/upload", "/api/branding/logo",
                       "/api/logs/review/upload", "/api/dem/import"],
        "extra_delete": ["/mcp"],
        "patterns_get": [
            "/api/tiles/{source}/{z:d}/{x:d}/{y:d}.png",
            "/api/buildings/{z:d}/{x:d}/{y:d}.json",
            "/api/plugins/asset/{id}/{rest*}",
        ],
    }
    write("python_routes.json", out)


COMMANDS = {"routes": routes}


def main(argv: list[str]) -> int:
    names = argv[1:] or ["all"]
    for name in names:
        if name == "all":
            for fn in COMMANDS.values():
                fn()
        elif name in COMMANDS:
            COMMANDS[name]()
        else:
            print(f"unknown command {name}; one of {', '.join(COMMANDS)} or all", file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
