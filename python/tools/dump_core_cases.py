def clean_nan(x):
    if isinstance(x, float) and x != x:
        return "nan"
    if isinstance(x, dict):
        return {k: clean_nan(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [clean_nan(v) for v in x]
    return x


