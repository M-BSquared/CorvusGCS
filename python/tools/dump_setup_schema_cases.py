def fields() -> None:
    from corvus import param_fields as F

    options = [{"value": 0, "label": "Off"}, {"value": 1, "label": "On"}]
    values = {"A": 1.0, "B": 2.0, "C": 0.5, "D": 2.5, "E": -1.5, "F": 3.5, "G": 7.0}
    out: dict = {"values": values, "options": options}
    out["enum"] = [[n, clean(F.enum(n, "Label", values, options, unit="x", hint="h"))]
                   for n in ["A", "B", "C", "D", "E", "F", "Z"]]
    out["enum_options"] = [[v, F.enum_options(options, v)] for v in (0.0, 1.0, 0.5, 1.5, 2.5, -0.5, -1.5, 7.0, 0.49)]
    out["labels"] = [[v, F.option_label(options, v)] for v in (0.0, 1.0, 0.5, 1.5, 2.5, -0.5, 9.0)]
    out["number"] = [[n, F.number(n, "Label", values, unit="m", step=1, min=0, max=1.5, hint="h", value=9)]
                     for n in ["A", "Z"]]
    bits = [{"bit": 0, "label": "One"}, {"bit": 1, "label": "Two"}]
    out["bitmask"] = [[n, F.bitmask(n, "Label", values, bits, hint="h")] for n in ["A", "Z"]]
    out["present"] = F.present([F.number("A", "a", values), None, F.number("Z", "z", values), F.number("B", "b", values)])
    fs = F.present([F.number("A", "a", values)])
    out["section"] = [F.section("id", "Title", fs), F.section("id", "Title", fs, "hint"), F.section("id", "T", [])]

    def sections(flow_state, rng):
        s = [{"id": "flow", "toggle": {"state": flow_state, "problems": ["x"]}} if flow_state else {"id": "flow"}]
        if rng is not None:
            s.append({"id": "rangefinder", "toggle": {"state": rng} if rng else None})
        return s

    flags = []
    for flow_state in (None, "on", "off", "partial"):
        for rng in (None, "on", "off", ""):
            data = sections(flow_state, rng)
            F.flag_flow_without_range(data)
            flags.append([sections(flow_state, rng), data])
    plain = [{"id": "flow", "toggle": {"state": "on"}}]
    F.flag_flow_without_range(plain)
    flags.append([[{"id": "flow", "toggle": {"state": "on"}}], plain])
    out["flags"] = flags
    write("setup_fields_cases.json", out)


COMMANDS = {"metadata": metadata, "fields": fields, "tables": tables, "safety": safety, "battery": battery}


def main(argv: list[str]) -> int:
    global CHECK
    args = [a for a in argv if not a.startswith("--")]
    CHECK = "--check" in argv
    names = list(COMMANDS) if args in ([], ["all"]) else args
    for name in names:
        if name not in COMMANDS:
            print(f"unknown command {name}; one of: all {' '.join(COMMANDS)}")
            return 2
        COMMANDS[name]()
    if CHECK and STALE:
        print("stale: " + ", ".join(STALE))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
