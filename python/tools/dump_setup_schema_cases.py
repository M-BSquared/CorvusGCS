"""Dump what the Python setup page schemas answer into fixtures for the Rust core.

    python tools/dump_setup_schema_cases.py metadata   -> src/core/tests/data/setup_metadata_cases.json
    python tools/dump_setup_schema_cases.py all
    python tools/dump_setup_schema_cases.py all --check   # fail when a file is stale

The Rust tests in ``src/core/tests/setup_*.rs`` hold ``corvus_core::setup_schemas``
to these files, so they are generated by running the Python, never typed. Run it
from ``python/`` with an interpreter that has corvus_link installed.
"""
