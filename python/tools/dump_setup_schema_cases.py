    add("px4 xz crc64", "px4-json", lzma.compress(plain, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64))
    add("px4 xz crc32", "px4-json", lzma.compress(plain, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC32))
