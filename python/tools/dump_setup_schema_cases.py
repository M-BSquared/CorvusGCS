STALE: list[str] = []
CHECK = False


def write(name: str, data: object, compact: bool = False) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    path = DATA / name
    text = (json.dumps(data, separators=(",", ":"), ensure_ascii=False) if compact
            else json.dumps(data, indent=1, sort_keys=False, ensure_ascii=False)) + "\n"
    if CHECK:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            STALE.append(name)
        return
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")


def clean(value: object) -> object:
    """What the wire carries: NaN and infinity as 0.0, tuples as lists."""
    from corvus.state_store import _sanitize

    return json.loads(json.dumps(_sanitize(value)))


def b64(raw: bytes) -> str:
    return base64.b64encode(raw).decode("ascii")


def _pck(entries: list[tuple[str, int, float, float | None]], *, magic: int = 0x671C,
         count: int | None = None, pad: bool = False) -> bytes:
    """A param.pck: (name, type 1..4, value, default or None)."""
    out = bytearray(struct.pack("<HHH", magic, len(entries) if count is None else count, len(entries)))
    last = b""
    fmts = {1: "<b", 2: "<h", 3: "<i", 4: "<f"}
    for name, kind, value, default in entries:
        raw = name.encode("ascii")
        common = 0
        while common < min(len(raw), len(last), 15) and raw[common] == last[common]:
            common += 1
        rest = raw[common:]
        flags = 1 if default is not None and magic == 0x671C else 0
        out.append(kind | (flags << 4))
        out.append(((len(rest) - 1) << 4) | common)
        out += rest
        out += struct.pack(fmts[kind], value)
        if flags:
            out += struct.pack(fmts[kind], default)
        last = raw
        if pad:
            out += b"\x00\x00"
    return bytes(out)


TABLES = PYTHON_ROOT.parent / "src" / "core" / "src" / "setup_schemas" / "data"


def write_table(name: str, data: object) -> None:
    """A static table the Rust schemas read, exported from the Python module that owns it."""
    TABLES.mkdir(parents=True, exist_ok=True)
    path = TABLES / name
    text = json.dumps(clean_keep(data), indent=1, ensure_ascii=False) + "\n"
    if CHECK:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            STALE.append(f"data/{name}")
        return
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")


def clean_keep(value: object) -> object:
    """JSON-safe: tuples and frozensets as lists, floats kept as floats."""
    if isinstance(value, (tuple, list)):
        return [clean_keep(v) for v in value]
    if isinstance(value, (set, frozenset)):
        return sorted(clean_keep(v) for v in value)
    if isinstance(value, dict):
        return {k: clean_keep(v) for k, v in value.items()}
    return value


