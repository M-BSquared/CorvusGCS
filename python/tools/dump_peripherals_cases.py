def ports() -> None:
    from corvus import serial_ports as sp

    cases = []
    for device in DEVICES:
        for hwid, desc in DESCRIPTORS:
            cases.append({
                "device": device, "hwid": hwid, "description": desc,
                "phantom": sp.is_phantom_device(device),
                "bootloader": sp.is_bootloader_port(device, hwid, desc),
                "rtk": sp.is_rtk_device(device, hwid, desc),
                "class": sp.classify_serial_device(device, hwid, desc),
            })
    out = {
        "cases": cases,
        "hwid_class": [{"hwid": h, "class": sp.classify_hwid(h)} for h, _ in DESCRIPTORS],
        "com": [{"device": d, "com": sp.is_windows_com_port(d)} for d in DEVICES],
        "split": [{"conn": c, "result": list(sp.split_serial_connection(c))} for c in CONNECTIONS],
        "identity": [{"hwid": h, "result": sp.usb_identity(h)} for h in HWIDS],
        "same": [
            {"a": a, "b": b, "same": sp.same_port(a, b)}
            for a in DEVICES[:30] for b in ("/dev/ttyACM0", "/dev/cu.usbmodem14201", "COM3", "\\\\.\\COM3", "")
        ],
        "present": [
            {"device": d, "enumerated": e, "present": sp.port_present(d, e)}
            for d, e in [
                ("", ["COM3"]), ("COM3", ["COM3"]), ("com3", ["\\\\.\\COM3"]), ("COM9", []),
                ("/dev/cu.usbmodem1", ["/dev/tty.usbmodem1"]), ("/dev/null", []), ("/dev/definitely-not-here", []),
                ("/dev/ttyACM0", ["/dev/ttyACM0", "/dev/ttyACM1"]),
            ]
        ],
        "default_baud": sp.DEFAULT_SERIAL_BAUD,
    }
    write("peripherals_ports_cases.json", out)


def netprobe() -> None:
    from corvus import net_probe as npb

    hosts = [
        "192.168.1.5", "example.com", "host_name", "-oProxyCommand=x", "a b", "", "  ", None, 5, "fe80::1%en0", "::1",
        "a" * 253, "a" * 254, "ok-host.local", "bad;rm", "trail-", "-lead", ":", "a:", "x" * 3 + "\n", "éx",
        "1.2.3.4 ", "[::1]", "a..b", "a%b", "9.9.9.9\n",
    ]
    cmds = []
    for plat in ("linux", "darwin", "win32"):
        for host in ("10.0.0.1", "fe80::1%en0", "host.local"):
            for wait in (0.5, 1.0, 2.0, 2.2, 10.0):
                cmds.append({
                    "platform": plat, "host": host, "wait": wait,
                    "argv": npb.ping_command("/bin/ping", host, wait, plat),
                })
    # ping6 is looked up on the PATH on macOS; pin it to what this machine says.
    replies = []
    texts = [
        "64 bytes from 10.0.0.1: icmp_seq=0 ttl=64 time=0.431 ms",
        "Reply from 10.0.0.1: bytes=32 time<1ms TTL=128",
        "Reply from 10.0.0.1: bytes=32 time=12ms TTL=128",
        "Reply from 10.0.0.9: Destination host unreachable.",
        "Reply from fe80::1: time=3ms",
        "Reply from fe80::1: Destination unreachable",
        "time=1,5 ms ttl=3", "", "rtt min/avg/max = 1.0/2.0/3.0 ms",
        "64 bytes from ::1: icmp_seq=1 ttl=64 time=0.05 ms",
    ]
    for plat in ("linux", "darwin", "win32"):
        for code in (0, 1, 2):
            for host in ("10.0.0.1", "::1"):
                for text in texts:
                    reachable, rtt = npb.parse_reply(code, text, host, plat)
                    replies.append({"platform": plat, "code": code, "host": host, "text": text,
                                    "reachable": reachable, "rtt": rtt})
    out = {
        "hosts": [{"host": h, "result": list(npb.clean_host(h))} for h in hosts if not isinstance(h, str) or True],
        "commands": [c for c in cmds if not (c["platform"] == "darwin" and ":" in c["host"])],
        "replies": replies,
        "limits": {"max_host": npb.MAX_HOST, "min_wait": npb.MIN_WAIT_S, "max_wait": npb.MAX_WAIT_S,
                   "grace": npb.GRACE_S, "concurrent": npb.MAX_CONCURRENT},
    }
    write("peripherals_netprobe_cases.json", out)


COMMANDS = {"ports": ports, "netprobe": netprobe}


def main(argv: list[str]) -> int:
    global CHECK
    CHECK = "--check" in argv
    names = [a for a in argv[1:] if a != "--check"] or ["all"]
    for name in names:
        if name == "all":
            for fn in COMMANDS.values():
                fn()
        elif name in COMMANDS:
            COMMANDS[name]()
        else:
            print(f"unknown command {name}; one of {', '.join(COMMANDS)} or all", file=sys.stderr)
            return 2
    if STALE:
        print("stale: " + ", ".join(STALE) + "; run tools/dump_peripherals_cases.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
