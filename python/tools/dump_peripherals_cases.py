"""Dump what the Python peripherals code answers into fixtures for the Rust core.

    python tools/dump_peripherals_cases.py ports      -> src/core/tests/data/peripherals_ports_cases.json
    python tools/dump_peripherals_cases.py all
    python tools/dump_peripherals_cases.py all --check   # fail when a file is stale

The peripherals area of ``corvus_core`` (radios, video, SSH, the local shell)
is held to these files by ``src/core/tests/peripherals_*.rs``. They are
generated by running the Python, never typed. Run it from ``python/`` with an
interpreter that has corvus_link installed.
"""
from __future__ import annotations

