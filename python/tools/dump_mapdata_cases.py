#!/usr/bin/env python3
"""Dump what the Python map data modules answer into fixtures for the Rust core.

    python tools/dump_mapdata_cases.py crs geocode      -> src/core/tests/data/mapdata_*.json
    python tools/dump_mapdata_cases.py all
    python tools/dump_mapdata_cases.py all --check      # fail when a file is stale

Same idea as ``dump_core_cases.py`` (the Rust tests of ``corvus_core::mapdata``
hold the port to these files, so they are generated by running the Python,
never typed), in a file of its own so the map data session and the other areas
do not edit the same script. Run it from ``python/`` with an interpreter that
has corvus_link installed.
"""
from __future__ import annotations

import json
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PYTHON_ROOT = HERE.parent
DATA = PYTHON_ROOT.parent / "src" / "core" / "tests" / "data"
sys.path.insert(0, str(PYTHON_ROOT))

STALE: list[str] = []
CHECK = False


def write(name: str, data: object) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    path = DATA / name
    text = json.dumps(data, indent=1, sort_keys=False, ensure_ascii=False) + "\n"
    if CHECK:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            STALE.append(name)
        return
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")


def crs_cases() -> None:
    from corvus import crs

    codes = [4326, 4258, 4269, 4283, 4167, 4617, 3857, 900913, 102100, 102113, 32601, 32632, 32633,
             32660, 32701, 32732, 32760, 25828, 25832, 25833, 25838, 26901, 26910, 26923, 5649, 4647,
             5650, 31466, 31467, 31468, 31469, 31492, 31493, 31494, 31495, 27700, 2154, 3035, 2056,
             21781, 1234, 0, -5, 25827, 25839, 32600, 32661]
    # Longitude and latitude of places each system is meant for, and a few it is not.
    points = [(11.5, 48.1), (8.2, 47.0), (-1.5, 52.4), (2.35, 48.85), (10.0, 52.0), (-74.0, 40.7),
              (151.2, -33.9), (0.0, 0.0), (13.4, 52.5), (-3.2, 55.9), (6.9, 46.2), (179.0, 60.0)]
    out = []
    for code in codes:
        c = crs.get(code)
        if c is None:
            out.append({"epsg": code, "known": False})
            continue
        rows = []
        for lon, lat in points:
            a, b = c.from_lonlat(lon, lat)
            back = c.to_lonlat(a, b)
            rows.append({"lon": lon, "lat": lat, "axes": [a, b], "back": list(back)})
        out.append({"epsg": code, "known": True, "name": c.name, "geographic": c.geographic,
                    "rows": rows})
    write("mapdata_crs_cases.json", {"codes": out, "hint": crs.SUPPORTED_HINT})


